CAD_UNITS = frozenset({'mm', 'cm', 'm', 'in', 'ft'})
CAD_PART_KINDS = frozenset({
    'box',
    'cylinder',
    'tube',
    'flange',
    'l_bracket',
    'plate_with_holes',
    'shaft',
    'enclosure',
})

FORBIDDEN_CODE_PATTERNS = re.compile(
    r'(?:\bimport\s+os\b|\bimport\s+subprocess\b|\brunpy\b|\beval\s*\(|\bexec\s*\(|__import__)',
    re.IGNORECASE,
)


class CadContractError(ValueError):
    """Raised when a GeometryTask violates parametric, security, or dimensional contracts."""


class CadWorkerTimeoutError(RuntimeError):
    """Raised when an isolated CAD worker exceeds its execution deadline and is terminated."""


def validate_geometry_task(task: Any) -> dict[str, Any]:
    """Validate a declarative parametric GeometryTask specification."""
    if not isinstance(task, dict):
        raise CadContractError('GeometryTask must be a JSON object')
    raw_json = json.dumps(task, ensure_ascii=False)
    if FORBIDDEN_CODE_PATTERNS.search(raw_json):
        raise CadContractError('Prohibited executable code pattern in GeometryTask (I-08)')
    if 'python_code' in task or 'script' in task or 'runpy' in task:
        raise CadContractError('Arbitrary script/runpy execution is prohibited in CAD Studio (I-08)')

    task_id = _check_id(task.get('task_id'), 'task_id')
    units = task.get('units')
    if units not in CAD_UNITS:
        raise CadContractError(f'CAD GeometryTask requires concrete physical units in {sorted(CAD_UNITS)}, got {units!r}')

    tol = task.get('tolerance_mm', 0.05)
    if type(tol) not in (int, float) or not math.isfinite(tol) or not (1e-4 <= float(tol) <= 10.0):
        raise CadContractError('tolerance_mm must be between 0.0001 and 10.0 mm')

    parts = task.get('parts')
    if not isinstance(parts, list) or not (1 <= len(parts) <= 128):
        raise CadContractError('GeometryTask.parts must contain 1..128 parametric parts')

    validated_parts: list[dict[str, Any]] = []
    seen_ids: set[str] = set()
    all_dimensions_verified = True

    for p in parts:
        if not isinstance(p, dict):
            raise CadContractError('Each CAD part must be an object')
        pid = _check_id(p.get('part_id'), 'part.part_id')
        if pid in seen_ids:
            raise CadContractError(f'Duplicate part_id: {pid}')
        seen_ids.add(pid)
        kind = p.get('kind')
        if kind not in CAD_PART_KINDS:
            raise CadContractError(f'Unsupported parametric part kind for {pid}: {kind!r}')
        name = str(p.get('name') or pid).strip()[:160]
        dims = p.get('dimensions')
        if not isinstance(dims, dict) or not dims:
            raise CadContractError(f'Part {pid} requires a non-empty dimensions dictionary')

        clean_dims: dict[str, float] = {}
        dim_sources: dict[str, str] = {}
        raw_sources = p.get('dimension_sources') if isinstance(p.get('dimension_sources'), dict) else {}

        for dkey, dval in dims.items():
            if type(dval) not in (int, float) or not math.isfinite(dval) or float(dval) <= 0:
                raise CadContractError(f'Dimension {dkey} on part {pid} must be a positive finite number')
            clean_dims[str(dkey)] = round(float(dval), 4)
            src = raw_sources.get(dkey, p.get('measured_source', 'assumed'))
            if src not in VALID_MEASURED_SOURCES:
                raise CadContractError(f'Invalid measured_source {src!r} for dimension {dkey} on {pid}')
            dim_sources[str(dkey)] = src
            if src in ('inferred', 'assumed'):
                all_dimensions_verified = False

        # Validate parametric constraints per part kind
        w, h, d = _part_bounding_dimensions(kind, clean_dims, pid)
        pos = p.get('position', [0.0, 0.0, 0.0])
        rot = p.get('rotation', [0.0, 0.0, 0.0])
        explode = p.get('explode_vector', [0.0, 0.0, 0.0])
        for vec_name, vec_val in (('position', pos), ('rotation', rot), ('explode_vector', explode)):
            if not isinstance(vec_val, list) or len(vec_val) != 3 or not all(type(x) in (int, float) and math.isfinite(x) for x in vec_val):
                raise CadContractError(f'Invalid {vec_name} on part {pid}')

        part_verified = all(s in ('observed', 'documented') for s in dim_sources.values())
        validated_parts.append({
            'part_id': pid,
            'name': name,
            'kind': kind,
            'dimensions': clean_dims,
            'dimension_sources': dim_sources,
            'bounding_box': [w, h, d],
            'position': [float(x) for x in pos],
            'rotation': [float(x) for x in rot],
            'explode_vector': [float(x) for x in explode],
            'material': str(p.get('material', 'aluminum_6061'))[:80],
            'color': str(p.get('color', '#64ffda'))[:16],
            'fidelity': 'cad_verified' if part_verified else 'conceptual',
            'measured_source': 'documented' if part_verified else 'inferred',
        })

    section = task.get('section_plane')
    clean_section = None
    if section is not None:
        if not isinstance(section, dict) or section.get('axis') not in ('X', 'Y', 'Z'):
            raise CadContractError("section_plane.axis must be 'X', 'Y', or 'Z'")
        offset = section.get('offset', 0.0)
        if type(offset) not in (int, float) or not math.isfinite(offset):
            raise CadContractError('section_plane.offset must be a finite number')
        clean_section = {'axis': section['axis'], 'offset': float(offset)}

    explode_factor = task.get('explode_factor', 0.0)
    if type(explode_factor) not in (int, float) or not math.isfinite(explode_factor) or not 0 <= explode_factor <= 1000:
        raise CadContractError('explode_factor must be finite and between 0 and 1000')
    return {
        'task_id': task_id,
        'units': units,
        'tolerance_mm': float(tol),
        'parts': validated_parts,
        'section_plane': clean_section,
        'explode_factor': float(explode_factor),
        'overall_fidelity': 'cad_verified' if all_dimensions_verified else 'conceptual',
        'engineering_verification_status': 'engineering-unverified',
    }


def _part_bounding_dimensions(kind: str, dims: dict[str, float], pid: str) -> tuple[float, float, float]:
    """Compute exact [width_x, height_y, depth_z] bounding box and verify geometric feasibility."""
    if kind in ('box', 'l_bracket', 'plate_with_holes', 'enclosure'):
        w = dims.get('width', dims.get('x', 0.0))
        h = dims.get('height', dims.get('y', 0.0))
        d = dims.get('depth', dims.get('thickness', dims.get('z', 0.0)))
        if w <= 0 or h <= 0 or d <= 0:
            raise CadContractError(f'Part {pid} ({kind}) requires positive width, height, and depth/thickness')
        if kind == 'plate_with_holes':
            hole_d = dims.get('hole_diameter', 0.0)
            if hole_d >= min(w, h):
                raise CadContractError(f'Part {pid}: hole_diameter ({hole_d}) cannot exceed plate width/height ({min(w, h)})')
        if kind == 'l_bracket':
            t = dims.get('thickness', min(w, h) * 0.2)
            if t >= min(w, h):
                raise CadContractError(f'Part {pid}: bracket thickness ({t}) must be smaller than width/height')
        return round(w, 4), round(h, 4), round(d, 4)

    if kind in ('cylinder', 'shaft', 'tube', 'flange'):
        radius = dims.get('radius', dims.get('diameter', 0.0) / 2.0)
        length = dims.get('length', dims.get('height', dims.get('thickness', 0.0)))
        if radius <= 0 or length <= 0:
            raise CadContractError(f'Part {pid} ({kind}) requires positive radius/diameter and length/height')
        if kind in ('tube', 'flange'):
            inner_r = dims.get('inner_radius', dims.get('bore_diameter', 0.0) / 2.0)
            if inner_r >= radius:
                raise CadContractError(f'Part {pid} ({kind}): inner_radius ({inner_r}) must be < outer radius ({radius})')
        return round(radius * 2.0, 4), round(length, 4), round(radius * 2.0, 4)

    raise CadContractError(f'Unhandled part kind: {kind}')


UNIT_METERS = {'mm': .001, 'cm': .01, 'm': 1., 'in': .0254, 'ft': .3048}


def _cadquery():
    try:
        import cadquery as cq
        return cq
    except ImportError as exc:
        raise CadContractError('CAD kernel unavailable: install requirements-cad.txt in the worker runtime') from exc


def _part_shape(part):
    cq = _cadquery()
    w, h, d = part['bounding_box']
    dims, kind = part['dimensions'], part['kind']
    if kind in {'cylinder', 'shaft', 'tube', 'flange'}:
        shape = cq.Solid.makeCylinder(w / 2, h, cq.Vector(0, -h / 2, 0), cq.Vector(0, 1, 0))
        inner = dims.get('inner_radius', dims.get('bore_diameter', 0) / 2)
        if kind in {'tube', 'flange'} and inner > 0:
            shape = shape.cut(cq.Solid.makeCylinder(inner, h, cq.Vector(0, -h / 2, 0), cq.Vector(0, 1, 0)))
    else:
        shape = cq.Workplane('XY').box(w, h, d).val()
        if kind == 'plate_with_holes' and dims.get('hole_diameter', 0) > 0:
            shape = shape.cut(cq.Solid.makeCylinder(dims['hole_diameter'] / 2, d, cq.Vector(0, 0, -d / 2)))
        elif kind == 'l_bracket':
            thickness = dims.get('thickness', min(w, h) * .2)
            cut = cq.Workplane('XY').box(w - thickness, h - thickness, d).val().translate((thickness / 2, thickness / 2, 0))
            shape = shape.cut(cut)
        elif kind == 'enclosure':
            thickness = dims.get('wall_thickness')
            if thickness is None or thickness * 2 >= min(w, h, d):
                raise CadContractError('Enclosure requires a documented wall_thickness smaller than half each dimension')
            cavity = cq.Workplane('XY').box(w - 2 * thickness, h - 2 * thickness, d - thickness).val().translate((0, 0, thickness / 2))
            shape = shape.cut(cavity)
    if not shape.isValid() or shape.Volume() <= 0:
        raise CadContractError('CAD kernel rejected a non-solid or invalid part')
    return shape


def _placed_shape(part, task):
    shape = _part_shape(part)
    for axis, angle in zip(((1, 0, 0), (0, 1, 0), (0, 0, 1)), part['rotation']):
        if angle:
            shape = shape.rotate((0, 0, 0), axis, math.degrees(angle))
    factor = task['explode_factor']
    return shape.translate(tuple(p + e * factor for p, e in zip(part['position'], part['explode_vector'])))


def generate_parametric_step_bytes(validated_task: dict[str, Any]) -> bytes:
    """Export actual OpenCascade solids; the worker never evaluates generated code."""
    import tempfile
    cq = _cadquery()
    shapes = [_placed_shape(part, validated_task) for part in validated_task['parts']]
    compound = cq.Compound.makeCompound(shapes)
    unit = {'mm': 'MM', 'cm': 'CM', 'm': 'M', 'in': 'INCH', 'ft': 'FT'}[validated_task['units']]
    with tempfile.TemporaryDirectory(prefix='axx-step-') as temp:
        path = Path(temp) / 'geometry.step'
        compound.exportStep(str(path), unit=unit)
        return path.read_bytes()


def validate_step_bytes(step_bytes: bytes) -> dict[str, Any]:
    """Reopen STEP with an independent OpenCascade reader and validate every solid."""
    import tempfile
    if not isinstance(step_bytes, (bytes, bytearray)) or len(step_bytes) < 64:
        raise CadContractError('STEP payload is empty or too short')
    cq = _cadquery()
    with tempfile.TemporaryDirectory(prefix='axx-step-read-') as temp:
        path = Path(temp) / 'geometry.step'
        path.write_bytes(step_bytes)
        try:
            shapes = cq.importers.importStep(str(path), unit='MM').solids().vals()
        except Exception as exc:
            raise CadContractError('OpenCascade could not reopen the STEP artifact') from exc
    if not shapes or any(not shape.isValid() or shape.Volume() <= 0 for shape in shapes):
        raise CadContractError('STEP artifact does not contain valid closed solids')
    solids = []
    for shape in shapes:
        box = shape.BoundingBox()
        solids.append({'bounding_box': [box.xlen, box.ylen, box.zlen], 'volume_mm3': shape.Volume()})
    return {'valid': True, 'units': 'mm', 'solid_count': len(solids), 'solids': solids,
            'sha256': hashlib.sha256(step_bytes).hexdigest(), 'size_bytes': len(step_bytes)}


def generate_parametric_glb_bytes(validated_task: dict[str, Any]) -> bytes:
    """Generate a standards-compliant binary glTF 2.0 (.glb) preview mesh congruent with the STEP solids."""
    nodes, meshes, views, accessors = [], [], [], []
    buffer = bytearray()
    scale = UNIT_METERS[validated_task['units']]
    for part in validated_task['parts']:
        shape = _placed_shape(part, validated_task)
        deflection = validated_task['tolerance_mm'] / (scale * 1000) / max(max(part['bounding_box']), 1) / 8
        vertices, triangles = shape.tessellate(deflection, .05)
        positions, normals = [], []
        # Face-local vertices preserve sharp edges and outward normals from the CAD tessellator.
        for triangle in triangles:
            a, b, c = [vertices[index] for index in triangle]
            normal = (b - a).cross(c - a).normalized()
            for vertex in (a, b, c):
                positions.extend([vertex.x * scale, vertex.y * scale, vertex.z * scale])
                normals.extend([normal.x, normal.y, normal.z])
        primitive = {}
        for semantic, values in [('POSITION', positions), ('NORMAL', normals)]:
            data = struct.pack(f'<{len(values)}f', *values)
            views.append({'buffer': 0, 'byteOffset': len(buffer), 'byteLength': len(data), 'target': 34962})
            buffer.extend(data)
            accessor = {'bufferView': len(views) - 1, 'componentType': 5126, 'count': len(values) // 3, 'type': 'VEC3'}
            if semantic == 'POSITION':
                accessor.update(min=[min(values[i::3]) for i in range(3)], max=[max(values[i::3]) for i in range(3)])
            accessors.append(accessor)
            primitive[semantic] = len(accessors) - 1
        box = shape.BoundingBox()
        # glTF is right-handed Y-up in metres; rotate Z-up CAD into that frame.
        nodes.append({'name': part['part_id'], 'mesh': len(meshes),
                      'rotation': [-math.sqrt(.5), 0, 0, math.sqrt(.5)],
                      'extras': {'part_id': part['part_id'], 'units': validated_task['units'],
                                 'bounding_box': [box.xlen, box.ylen, box.zlen], 'fidelity': part['fidelity']}})
        meshes.append({'name': part['name'], 'primitives': [{'attributes': primitive}]})
    gltf = {'asset': {'version': '2.0', 'generator': 'AXX CAD OpenCascade'}, 'scene': 0,
            'scenes': [{'nodes': list(range(len(nodes)))}], 'nodes': nodes, 'meshes': meshes,
            'buffers': [{'byteLength': len(buffer)}], 'bufferViews': views, 'accessors': accessors}
    json_bytes = json.dumps(gltf, separators=(',', ':'), ensure_ascii=False).encode('utf-8')
    json_bytes += b' ' * (-len(json_bytes) % 4)
    total = 12 + 8 + len(json_bytes) + 8 + len(buffer)
    return (struct.pack('<III', 0x46546C67, 2, total) + struct.pack('<II', len(json_bytes), 0x4E4F534A)
            + json_bytes + struct.pack('<II', len(buffer), 0x004E4942) + buffer)


def validate_glb_bytes(glb_bytes: bytes) -> dict[str, Any]:
    """Validate binary glTF 2.0 header, chunks, and extract node bounding boxes."""
    if not isinstance(glb_bytes, (bytes, bytearray)) or len(glb_bytes) < 28:
        raise CadContractError('GLB payload is empty or too short')
    magic, version, total_len = struct.unpack('<III', glb_bytes[:12])
    if magic != 0x46546C67 or version != 2 or total_len != len(glb_bytes):
        raise CadContractError('Invalid glTF 2.0 binary header')
    json_len, json_type = struct.unpack('<II', glb_bytes[12:20])
    if json_type != 0x4E4F534A:
        raise CadContractError('Missing JSON chunk in GLB')
    gltf = json.loads(glb_bytes[20:20 + json_len].decode('utf-8'))
    nodes = gltf.get('nodes') or []
    binary_offset = 20 + json_len
    if binary_offset + 8 > len(glb_bytes):
        raise CadContractError('Missing GLB binary chunk')
    bin_len, bin_type = struct.unpack('<II', glb_bytes[binary_offset:binary_offset + 8])
    if bin_type != 0x004E4942 or binary_offset + 8 + bin_len != len(glb_bytes):
        raise CadContractError('Invalid GLB binary chunk')
    binary = glb_bytes[binary_offset + 8:]
    for node in nodes:
        primitive = gltf['meshes'][node['mesh']]['primitives'][0]
        accessor = gltf['accessors'][primitive['attributes']['POSITION']]
        view = gltf['bufferViews'][accessor['bufferView']]
        if accessor['componentType'] != 5126 or accessor['type'] != 'VEC3':
            raise CadContractError('Unsupported CAD mesh position format')
        offset = view.get('byteOffset', 0) + accessor.get('byteOffset', 0)
        size = accessor['count'] * 12
        if size <= 0 or offset + size > len(binary):
            raise CadContractError('CAD mesh accessor exceeds the binary buffer')
        vertices = struct.unpack_from(f"<{accessor['count'] * 3}f", binary, offset)
        node['mesh_bounds_mm'] = [(max(vertices[i::3]) - min(vertices[i::3])) * 1000 for i in range(3)]
    return {
        'valid': True,
        'node_count': len(nodes),
        'nodes': nodes,
        'sha256': hashlib.sha256(glb_bytes).hexdigest(),
        'size_bytes': len(glb_bytes),
    }


def verify_step_glb_congruence(
    step_bytes: bytes,
    glb_bytes: bytes,
    *,
    tolerance_mm: float = 0.05,
) -> dict[str, Any]:
    """Verify that the STEP solids and GLB mesh nodes have congruent count and dimensions (MP-03)."""
    step_info = validate_step_bytes(step_bytes)
    glb_info = validate_glb_bytes(glb_bytes)
    if step_info['solid_count'] != glb_info['node_count']:
        raise CadContractError(
            f"STEP/GLB solid count mismatch: STEP={step_info['solid_count']}, GLB={glb_info['node_count']}"
        )
    max_delta = 0.0
    for solid, node in zip(step_info['solids'], glb_info['nodes']):
        s_box = solid['bounding_box']
        g_box = node.get('mesh_bounds_mm')
        if not isinstance(g_box, list) or len(g_box) != 3:
            raise CadContractError('GLB node missing bounding_box metadata')
        for sv, gv in zip(s_box, g_box):
            delta = abs(float(sv) - float(gv))
            max_delta = max(max_delta, delta)
            if delta > tolerance_mm:
                raise CadContractError(
                    f'STEP/GLB dimensional divergence {delta:.4f} exceeds tolerance {tolerance_mm:.4f}'
                )
    return {
        'congruent': True,
        'solid_count': step_info['solid_count'],
        'max_dimensional_delta': round(max_delta, 6),
        'step_sha256': step_info['sha256'],
        'glb_sha256': glb_info['sha256'],
    }


def execute_cad_geometry_task(
    task: dict[str, Any],
    *,
    output_dir: str | Path | None = None,
    document_id: str | None = None,
    source_id: str = 'cad-spec-1',
) -> dict[str, Any]:
    """Execute a validated parametric GeometryTask, write STEP/GLB artifacts, and build SceneDocument v2."""
    validated = validate_geometry_task(task)
    step_bytes = generate_parametric_step_bytes(validated)
    glb_bytes = generate_parametric_glb_bytes(validated)
    congruence = verify_step_glb_congruence(
        step_bytes,
        glb_bytes,
        tolerance_mm=validated['tolerance_mm'],
    )

    step_sha = congruence['step_sha256']
    glb_sha = congruence['glb_sha256']
    step_path_str = None
    glb_path_str = None

    if output_dir is not None:
        out = Path(output_dir)
        out.mkdir(parents=True, exist_ok=True)
        step_file = out / f"cad-{step_sha[:24]}.step"
        glb_file = out / f"cad-{glb_sha[:24]}.glb"
        step_file.write_bytes(step_bytes)
        glb_file.write_bytes(glb_bytes)
        step_path_str = str(step_file)
        glb_path_str = str(glb_file)

    step_asset_id = f"asset-step-{validated['task_id']}"
    glb_asset_id = f"asset-glb-{validated['task_id']}"
    assets = [
        {
            'asset_id': step_asset_id,
            'sha256': step_sha,
            'mime_type': 'model/step',
            'size_bytes': len(step_bytes),
            'license': 'internal',
        },
        {
            'asset_id': glb_asset_id,
            'sha256': glb_sha,
            'mime_type': 'model/gltf-binary',
            'size_bytes': len(glb_bytes),
            'license': 'internal',
        },
    ]

    objects = []
    for p in validated['parts']:
        objects.append({
            'id': p['part_id'],
            'name': p['name'],
            'representation': 'brep',
            'fidelity': p['fidelity'],
            'measured_source': p['measured_source'],
            'geometry_asset_id': step_asset_id,
            'transform': {
                'position': p['position'],
                'rotation': p['rotation'],
                'scale': [1.0, 1.0, 1.0],
            },
            'properties': {
                'kind': p['kind'],
                'dimensions': p['dimensions'],
                'dimension_sources': p['dimension_sources'],
                'bounding_box': p['bounding_box'],
                'preview_glb_asset_id': glb_asset_id,
                'material': p['material'],
                'color': p['color'],
                'explode_vector': p['explode_vector'],
                'engineering_verification_status': 'engineering-unverified',
            },
        })

    scene_doc = validate_scene_document_v2({
        'schema_version': '2.0',
        'document_id': document_id or f"cad-scene-{validated['task_id']}",
        'revision': 1,
        'mode': 'cad',
        'units': validated['units'],
        'fidelity': validated['overall_fidelity'],
        'coordinate_system': {'up_axis': 'Z', 'handedness': 'right', 'origin': [0.0, 0.0, 0.0]},
        'source': {'kind': 'user_spec', 'source_id': source_id, 'revision': 1},
        'objects': objects,
        'assets': assets,
        'timeline': {'duration_seconds': 0.0, 'tracks': []},
        'metadata': {
            'tolerance_mm': validated['tolerance_mm'],
            'section_plane': validated['section_plane'],
            'explode_factor': validated['explode_factor'],
            'engineering_verification_status': 'engineering-unverified',
            'congruence': congruence,
        },
    })

    return {
        'task_id': validated['task_id'],
        'scene_document': scene_doc,
        'step_bytes': step_bytes,
        'glb_bytes': glb_bytes,
        'step_path': step_path_str,
        'glb_path': glb_path_str,
        'congruence': congruence,
        'diagnostic_report': {
            'overall_fidelity': validated['overall_fidelity'],
            'engineering_verification_status': 'engineering-unverified',
            'units': validated['units'],
            'tolerance_mm': validated['tolerance_mm'],
            'part_count': len(validated['parts']),
            'inferred_dimensions_present': validated['overall_fidelity'] != 'cad_verified',
        },
    }


class IsolatedCadWorker:
    """Supervises an isolated subprocess running parametric CAD tasks with timeout, kill, and recovery."""

    def __init__(self, worker_script: str | Path | None = None, timeout_seconds: float = 45.0):
        base = Path(getattr(sys, '_MEIPASS', Path(__file__).resolve().parents[2]))
        self.worker_script = Path(worker_script or (base / 'workers' / 'cad-worker' / 'worker.py'))
        self.timeout_seconds = float(timeout_seconds)
        self.last_crash_recovered = False

    def run_task(
        self,
        task: dict[str, Any],
        *,
        output_dir: str | Path,
        timeout_override: float | None = None,
    ) -> dict[str, Any]:
        validated = validate_geometry_task(task)
        payload = json.dumps({
            'task': task,
            'output_dir': str(output_dir),
        }, ensure_ascii=False).encode('utf-8')
        timeout = float(timeout_override if timeout_override is not None else self.timeout_seconds)
        if getattr(sys, 'frozen', False):
            cmd = [sys.executable, '--cad-worker']
        else:
            cmd = [sys.executable, str(self.worker_script)]
        proc = subprocess.Popen(
            cmd,
            stdin=subprocess.PIPE,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
        )
        try:
            stdout, stderr = proc.communicate(input=payload, timeout=timeout)
        except subprocess.TimeoutExpired as exc:
            proc.kill()
            proc.wait(timeout=5)
            self.last_crash_recovered = True
            raise CadWorkerTimeoutError(
                f"Isolated CAD worker timed out after {timeout}s on task {validated['task_id']} and was terminated"
            ) from exc

        if proc.returncode != 0:
            self.last_crash_recovered = True
            err_msg = stderr.decode('utf-8', errors='replace').strip()
            raise CadContractError(f'Isolated CAD worker exited with code {proc.returncode}: {err_msg}')

        response = json.loads(stdout.decode('utf-8'))
        if not response.get('ok'):
            raise CadContractError(response.get('error', 'CAD worker returned failure'))
        return response['result']


def worker_main() -> int:
    """Entrypoint for isolated CAD worker subprocess (used by both workers/cad-worker/worker.py and frozen axx-backend.exe --cad-worker)."""
    import time
    try:
        raw = sys.stdin.buffer.read().decode('utf-8')
        request = json.loads(raw)
        task = request.get('task') or {}
        if task.get('_simulate_hang_seconds'):
            time.sleep(float(task['_simulate_hang_seconds']))
        output_dir = request.get('output_dir')
        res = execute_cad_geometry_task(task, output_dir=output_dir)
        serializable = {
            'task_id': res['task_id'],
            'scene_document': res['scene_document'],
            'step_path': res['step_path'],
            'glb_path': res['glb_path'],
            'congruence': res['congruence'],
            'diagnostic_report': res['diagnostic_report'],
        }
        sys.stdout.write(json.dumps({'ok': True, 'result': serializable}, ensure_ascii=False))
        return 0
    except Exception as exc:
        sys.stdout.write(json.dumps({'ok': False, 'error': str(exc)}, ensure_ascii=False))
        return 1
