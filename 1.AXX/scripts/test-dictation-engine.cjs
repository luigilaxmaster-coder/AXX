const assert = require('node:assert/strict');
const { Segmenter, wav, settings, processText, shortcutChord } = require('./dictation-engine.js');
const rate = 16000, frame = value => new Float32Array(1600).fill(value), segments = [];
const detector = new Segmenter(rate, (pcm, rate, target) => segments.push({ pcm, rate, target }));
for (let i = 0; i < 10; i++) detector.feed(frame(0), 'a');
assert.equal(segments.length, 0);
for (let i = 0; i < 5; i++) detector.feed(frame(.02), 'a');
for (let i = 0; i < 8; i++) detector.feed(frame(0), 'a');
assert.equal(segments.length, 1); assert.equal(segments[0].target, 'a');
for (let i = 0; i < 6; i++) detector.feed(frame(.02), 'a');
detector.feed(frame(.02), 'b');
assert.equal(segments.length, 2); assert.equal(segments[1].target, 'a');
for (let i = 0; i < 8; i++) detector.feed(frame(0), 'b');
assert.equal(segments.length, 3); assert.equal(segments[2].target, 'b');
for (let i = 0; i < 250; i++) detector.feed(frame(.02), 'b');
assert.ok(segments.length >= 5, 'A long utterance must split into bounded segments');
assert.ok(segments.every(s => s.pcm.length <= rate * 10.2));
const buffer = wav(new Float32Array([-1, 0, 1]), rate), view = new DataView(buffer);
assert.equal(buffer.byteLength, 50); assert.equal(view.getUint32(24, true), rate); assert.equal(view.getInt16(44, true), -32767);
assert.throws(() => settings({ approved: true })); assert.throws(() => settings({ dictionary: [['x', '\n']] }));
assert.deepEqual(shortcutChord('Ctrl+Alt+Shift+D', 'hold'), { key: 68, modifiers: 7, activation: 'hold' });
assert.throws(() => shortcutChord('Ctrl+Ctrl+D', 'toggle')); assert.throws(() => shortcutChord('Ctrl+Enter', 'toggle'));
assert.throws(() => settings({ dictionary: Array(101).fill(['a', 'b']) }));
const config = settings({ profile: 'technical', dictionary: [['axx', 'AXX'], ['c++', 'C++'], ['uno', '1']] });
assert.equal(processText('axx: c++; uno, ninguno, 1.25 mg', config), 'AXX: C++; 1, ninguno, 1.25 mg');
assert.equal(processText('  axx uno 1.25 mg', { ...config, profile: 'literal' }), '  axx uno 1.25 mg');
assert.equal(processText('axx uno', { ...config, profile: 'code' }), 'axx uno');
detector.reset(); assert.equal(detector.samples, 0); assert.equal(detector.frames.length, 0);
console.log('PASS: PCM/WAV, calibrated VAD, sustained segments, bounded audio, focus binding, literal/code, deterministic dictionary and configuration guards');
