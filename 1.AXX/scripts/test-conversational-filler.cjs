const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), vm = require('node:vm');
const Axx = {};
vm.runInNewContext(fs.readFileSync(path.join(__dirname,'voice-conversation.js'),'utf8'),{window:{Axx}});
const voice = Axx.voiceConversation;
assert.equal(voice.phraseLength('Sí. Seguimos'),'Sí.'.length);
assert.equal(voice.phraseLength('Cuesta 2.50 euros. Luego sigo'),'Cuesta 2.50 euros.'.length);
assert.equal(voice.phraseLength('El Dr. Pérez llegará pronto. Seguimos'),'El Dr. Pérez llegará pronto.'.length);
assert.equal(voice.phraseLength('Todavía estoy escribiendo'),0);
assert.equal(voice.phraseLength('Texto final',true),11);
assert.equal(voice.phraseLength('x'.repeat(200)),0);
assert.equal(voice.phraseLength('x'.repeat(200),true),200);
const long = 'Esta es una frase larga, ' + 'palabra '.repeat(40);
const size=voice.phraseLength(long);
assert(size>0 && size<=180 && long[size]===' ');
let endings=0;const reader={state:'waiting',awaitingText:true,onEnded(){endings++;}};
voice.finish(reader);assert.equal(reader.state,'ended');assert.equal(reader.awaitingText,false);assert.equal(endings,1);
voice.finish(reader);assert.equal(endings,1);
const source=fs.readFileSync(path.join(__dirname,'../Axx.html'),'utf8');
assert(!source.includes('startLoadingAudio'));
assert(!source.includes('scripts/conversational-filler.js'));
assert(!source.includes('id="chat-loading-sound"'));
assert(!source.includes('max_tokens: 80'));
console.log('PASS: natural phrasing, decimals and titles, bounded chunks, final flush, once-only stream completion and silent waiting');
